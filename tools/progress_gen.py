#!/usr/bin/env python3
"""Generate the live progress page for moh-vanguard-recomp.

Reads  docs/progress.json
Writes docs/progress.svg
       docs/progress.html

Python 3.8+, stdlib only. Run from anywhere:

    python tools/progress_gen.py

The generated artifacts are committed, and GitHub Pages (source: main /docs)
publishes the docs/ directory at the site root — so the page is live at
https://lesandrossb.github.io/moh-vanguard-recomp/progress.html on every push,
no CI needed. GitHub's branch source only accepts / or /docs, hence docs/ root.

TODO(ci): add .github/workflows/progress.yml to re-run this generator on push
to main and commit any regenerated diff under docs/ (fail the run if the
committed artifacts are stale), so the page can never drift from progress.json.
"""
import json
import sys
from html import escape
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
DATA = ROOT / "docs" / "progress.json"
SVG_OUT = ROOT / "docs" / "progress.svg"
HTML_OUT = ROOT / "docs" / "progress.html"

# GitHub-dark surface + status palette. Status colors are never used alone:
# every mark also carries geometry (solid / hollow / pulsing) and a text label.
BG = "#0d1117"
BORDER = "#30363d"
INK = "#e6edf3"
BODY = "#c9d1d9"
MUTED = "#8b949e"
DONE = "#2ea043"
FRONTIER = "#d29922"
PARTIAL = "#e3b341"
CELL_OFF = "#21262d"
FONT = "ui-sans-serif, system-ui, 'Segoe UI', Helvetica, Arial, sans-serif"

STATUS_WORD = {
    "done": "cleared",
    "current": "CURRENT",
    "frontier": "FRONTIER",
    "partial": "PARTIAL",
    "future": "not reached",
}

SVG_CSS = """<style>
.pulse{animation:vgpulse 2.2s ease-in-out infinite}
.pulse2{animation:vgpulse 2.2s ease-in-out .28s infinite}
.pulse3{animation:vgpulse 2.2s ease-in-out .56s infinite}
.pulse4{animation:vgpulse 2.2s ease-in-out .84s infinite}
@keyframes vgpulse{0%,100%{opacity:1}50%{opacity:.32}}
@media (prefers-reduced-motion:reduce){.pulse,.pulse2,.pulse3,.pulse4{animation:none}}
</style>"""

PULSE_CLASSES = ["pulse", "pulse2", "pulse3", "pulse4"]


def esc(s):
    return escape(str(s), quote=True)


# --------------------------------------------------------------------------
# progress.svg — expedition path (top) + subsystem cell grid (below)
# --------------------------------------------------------------------------

def build_svg(data):
    W = 1280
    stages = data["stages"]
    subs = data["subsystems"]
    n = len(stages)
    cur = next(i for i, s in enumerate(stages) if s["status"] == "current")

    p = []  # svg parts

    # --- header -----------------------------------------------------------
    p.append(f'<text x="48" y="52" fill="{INK}" font-size="22" font-weight="700" font-family="{FONT}">{esc(data["project"])} — expedition</text>')
    p.append(f'<text x="48" y="76" fill="{MUTED}" font-size="13" font-family="{FONT}">PS2 static recomp · live progress map · updated {esc(data["updated"])}</text>')
    p.append(f'<text x="1232" y="76" fill="{MUTED}" font-size="12" text-anchor="end" font-family="{FONT}">generated by tools/progress_gen.py</text>')

    # --- section A: the expedition path ------------------------------------
    p.append(f'<text x="48" y="118" fill="{MUTED}" font-size="11" font-weight="700" letter-spacing="2" font-family="{FONT}">THE EXPEDITION PATH</text>')
    p.append(f'<text x="1232" y="118" fill="{MUTED}" font-size="11" text-anchor="end" font-family="{FONT}">green = cleared · orange = the frontier · gray = ahead</text>')

    yline = 196
    xs = [88 + i * (W - 2 * 88) / (n - 1) for i in range(n)]

    # connecting line, colored by travel: green up to the frontier, orange
    # into it, dashed gray beyond it. Arrowheads mark direction.
    p.append(f'''<defs>
<marker id="ag" viewBox="0 0 10 10" refX="8" refY="5" markerWidth="7" markerHeight="7" orient="auto-start-reverse"><path d="M0,0 L10,5 L0,10 z" fill="{DONE}"/></marker>
<marker id="ao" viewBox="0 0 10 10" refX="8" refY="5" markerWidth="7" markerHeight="7" orient="auto-start-reverse"><path d="M0,0 L10,5 L0,10 z" fill="{FRONTIER}"/></marker>
<marker id="am" viewBox="0 0 10 10" refX="8" refY="5" markerWidth="7" markerHeight="7" orient="auto-start-reverse"><path d="M0,0 L10,5 L0,10 z" fill="{MUTED}"/></marker>
</defs>''')
    for i in range(n - 1):
        x0, x1 = xs[i], xs[i + 1]
        # shrink the segment so the arrowhead lands before the next node
        x1 -= 24 if i + 1 != cur else 26
        if i + 1 < cur:
            p.append(f'<line x1="{x0:.1f}" y1="{yline}" x2="{x1:.1f}" y2="{yline}" stroke="{DONE}" stroke-width="3" marker-end="url(#ag)"/>')
        elif i + 1 == cur:
            p.append(f'<line x1="{x0:.1f}" y1="{yline}" x2="{x1:.1f}" y2="{yline}" stroke="{FRONTIER}" stroke-width="3" marker-end="url(#ao)"/>')
        else:
            p.append(f'<line x1="{x0:.1f}" y1="{yline}" x2="{x1:.1f}" y2="{yline}" stroke="{MUTED}" stroke-width="2" stroke-dasharray="5 6" marker-end="url(#am)"/>')

    for i, s in enumerate(stages):
        x = xs[i]
        st = s["status"]
        tip = esc(f'{s["name"]} — {s["evidence_full"]}')
        if st == "done":
            p.append(f'<g><title>{tip}</title><circle cx="{x:.1f}" cy="{yline}" r="15" fill="{BG}"/><circle cx="{x:.1f}" cy="{yline}" r="13" fill="{DONE}"/>'
                     f'<text x="{x:.1f}" y="{yline + 4:.1f}" fill="#ffffff" font-size="11" font-weight="700" text-anchor="middle" font-family="{FONT}">{i + 1}</text></g>')
            name_fill, ev_fill = INK, MUTED
        elif st == "current":
            p.append(f'<g><title>{tip}</title>'
                     f'<circle cx="{x:.1f}" cy="{yline}" r="22" fill="none" stroke="{FRONTIER}" stroke-width="2" class="pulse"/>'
                     f'<circle cx="{x:.1f}" cy="{yline}" r="15" fill="{BG}"/><circle cx="{x:.1f}" cy="{yline}" r="13" fill="{FRONTIER}"/>'
                     f'<text x="{x:.1f}" y="{yline + 4:.1f}" fill="#0d1117" font-size="11" font-weight="700" text-anchor="middle" font-family="{FONT}">{i + 1}</text></g>')
            name_fill, ev_fill = FRONTIER, FRONTIER
        else:
            p.append(f'<g><title>{tip}</title><circle cx="{x:.1f}" cy="{yline}" r="13" fill="{CELL_OFF}" stroke="{BORDER}" stroke-width="1.5"/>'
                     f'<text x="{x:.1f}" y="{yline + 4:.1f}" fill="{MUTED}" font-size="11" font-weight="700" text-anchor="middle" font-family="{FONT}">{i + 1}</text></g>')
            name_fill, ev_fill = MUTED, MUTED
        if st == "current":
            p.append(f'<text x="{x:.1f}" y="{yline - 34}" fill="{FRONTIER}" font-size="10.5" font-weight="700" letter-spacing="1.5" text-anchor="middle" font-family="{FONT}" class="pulse">CURRENT</text>')
        p.append(f'<text x="{x:.1f}" y="{yline + 36}" fill="{name_fill}" font-size="12.5" font-weight="600" text-anchor="middle" font-family="{FONT}">{esc(s["name"])}</text>')
        p.append(f'<text x="{x:.1f}" y="{yline + 53}" fill="{ev_fill}" font-size="10.5" text-anchor="middle" font-family="{FONT}">{esc(s["evidence"])}</text>')

    # --- section B: the subsystem grid -------------------------------------
    ysec = 306
    p.append(f'<text x="48" y="{ysec}" fill="{MUTED}" font-size="11" font-weight="700" letter-spacing="2" font-family="{FONT}">SUBSYSTEM GRID</text>')
    p.append(f'<text x="1232" y="{ysec}" fill="{MUTED}" font-size="11" text-anchor="end" font-family="{FONT}">hover any row for the one-liner</text>')

    y0 = ysec + 26
    rh = 34
    label_x = 252       # right-aligned subsystem name
    cells_x = 268       # cell strip starts
    cell_w, cell_h, gap = 22, 20, 6
    max_cells = max(s.get("cells", 5) for s in subs)
    one_x = cells_x + max_cells * (cell_w + gap) + 12  # one-liner column
    status_x = 1232     # right-aligned status word — identity is never color-alone

    for r, s in enumerate(subs):
        cy = y0 + r * rh + rh / 2
        st = s["status"]
        word = STATUS_WORD[st]
        tip = esc(f'{s["name"]} — {s["one_liner"]} ({word.lower() if st != "current" else "the active frontier"})')
        row = [f'<g><title>{tip}</title>']
        row.append(f'<text x="{label_x}" y="{cy + 4:.1f}" fill="{BODY}" font-size="12.5" font-weight="600" text-anchor="end" font-family="{FONT}">{esc(s["name"])}</text>')
        for c in range(s.get("cells", 5)):
            cx = cells_x + c * (cell_w + gap)
            if st == "done":
                row.append(f'<rect x="{cx}" y="{cy - cell_h / 2:.1f}" width="{cell_w}" height="{cell_h}" rx="5" fill="{DONE}"/>')
            elif st == "frontier":
                row.append(f'<rect x="{cx}" y="{cy - cell_h / 2:.1f}" width="{cell_w}" height="{cell_h}" rx="5" fill="{FRONTIER}" class="{PULSE_CLASSES[c % 4]}"/>')
            elif st == "partial":
                row.append(f'<rect x="{cx}" y="{cy - cell_h / 2:.1f}" width="{cell_w}" height="{cell_h}" rx="5" fill="{BG}" stroke="{PARTIAL}" stroke-width="1.8"/>')
            else:
                row.append(f'<rect x="{cx}" y="{cy - cell_h / 2:.1f}" width="{cell_w}" height="{cell_h}" rx="5" fill="{CELL_OFF}" stroke="{BORDER}"/>')
        one_fill = FRONTIER if st == "frontier" else MUTED
        row.append(f'<text x="{one_x}" y="{cy + 4:.1f}" fill="{one_fill}" font-size="11" font-family="{FONT}">{esc(s["one_liner"])}</text>')
        if st == "frontier":
            row.append(f'<text x="{status_x}" y="{cy + 4:.1f}" fill="{FRONTIER}" font-size="10" font-weight="700" letter-spacing="1" text-anchor="end" font-family="{FONT}" class="pulse">{word}</text>')
        elif st == "partial":
            row.append(f'<text x="{status_x}" y="{cy + 4:.1f}" fill="{PARTIAL}" font-size="10" font-weight="700" letter-spacing="1" text-anchor="end" font-family="{FONT}">{word}</text>')
        elif st == "future":
            row.append(f'<text x="{status_x}" y="{cy + 4:.1f}" fill="{MUTED}" font-size="10" font-weight="600" letter-spacing="1" text-anchor="end" font-family="{FONT}">{word}</text>')
        else:
            row.append(f'<text x="{status_x}" y="{cy + 4:.1f}" fill="{DONE}" font-size="10" font-weight="600" letter-spacing="1" text-anchor="end" font-family="{FONT}">{word}</text>')
        row.append('</g>')
        p.append(''.join(row))

    # --- legend -------------------------------------------------------------
    yleg = y0 + len(subs) * rh + 26
    lx = 48
    items = [
        ("solid", DONE, None, "cleared"),
        ("solid", FRONTIER, "pulse", "the frontier — active research"),
        ("hollow", PARTIAL, None, "partial"),
        ("off", None, None, "not reached"),
    ]
    for kind, color, anim, label in items:
        if kind == "solid":
            cls = f' class="{anim}"' if anim else ''
            p.append(f'<rect x="{lx}" y="{yleg - 11}" width="18" height="14" rx="4" fill="{color}"{cls}/>')
        elif kind == "hollow":
            p.append(f'<rect x="{lx}" y="{yleg - 11}" width="18" height="14" rx="4" fill="{BG}" stroke="{color}" stroke-width="1.6"/>')
        else:
            p.append(f'<rect x="{lx}" y="{yleg - 11}" width="18" height="14" rx="4" fill="{CELL_OFF}" stroke="{BORDER}"/>')
        p.append(f'<text x="{lx + 26}" y="{yleg}" fill="{BODY}" font-size="11.5" font-family="{FONT}">{esc(label)}</text>')
        lx += 26 + len(label) * 6.4 + 34
    p.append(f'<text x="1232" y="{yleg}" fill="{MUTED}" font-size="11" text-anchor="end" font-family="{FONT}">color is never the only signal: every row is labeled, tooltipped and pulse-animated</text>')

    H = yleg + 30

    svg_body = (
        f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 {W} {H}" width="{W}" height="{H}" role="img" '
        f'aria-label="Progress map: expedition path with 6 of 10 stages cleared, currently at the Front-End Gate, and a subsystem grid">'
        f'{SVG_CSS}<rect x="1" y="1" width="{W - 2}" height="{H - 2}" rx="12" fill="{BG}" stroke="{BORDER}"/>' + ''.join(p) + '</svg>'
    )
    return svg_body


# --------------------------------------------------------------------------
# progress.html
# --------------------------------------------------------------------------

