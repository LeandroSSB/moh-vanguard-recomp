BADGE = {
    "done": '<span class="badge b-done"><i></i>cleared</span>',
    "current": '<span class="badge b-cur"><i></i>current</span>',
    "future": '<span class="badge b-fut"><i></i>not reached</span>',
}


def build_html(data, svg_body):
    d = data
    stage_rows = []
    for s in d["stages"]:
        stage_rows.append(
            f'<tr><td>{esc(s["name"])}</td><td>{BADGE[s["status"]]}</td>'
            f'<td>{esc(s["evidence_full"])}</td><td class="mono">{esc(s["unblocked_by"])}</td></tr>'
        )
    pr_rows = []
    for f in d["fixes"]["upstream"]:
        url = f'{d["links"]["repo"].replace("LeandroSSB/moh-vanguard-recomp", d["fixes"]["upstream_base"])}/pull/{f["pr"]}'
        pr_rows.append(
            f'<tr><td><a href="{url}">#{f["pr"]}</a></td><td>{esc(f["title"])}</td><td class="mono">{esc(f["detail"])}</td></tr>'
        )
    branch_items = []
    for f in d["fixes"]["branch_only"]:
        note = ' <span class="badge b-cur"><i></i>landing</span>' if f.get("note") == "landing" else ''
        branch_items.append(f'<li><span>{esc(f["name"])}{note}</span></li>')

    stats = ''.join(f'<div class="stat"><b>{esc(s["value"])}</b><span>{esc(s["label"])}</span></div>' for s in d["stats"])

    return f"""<!DOCTYPE html>
<html lang="en">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1">
<title>{esc(d["project"])} — progress</title>
<style>{HTML_CSS}</style>
</head>
<body>
<main>
  <h1>{esc(d["project"])}</h1>
  <p class="sub">Native PC port via <a href="{esc(d["upstream_url"])}">{esc(d["fixes"]["upstream_base"])}</a> · this page: <a href="{esc(d["pages_url"])}">{esc(d["pages_url"].replace("https://", ""))}</a></p>

  <div class="banner">
    <strong>&#9888;&#65039; {esc(d["status_line"])}</strong>
    <p>{esc(d["status_note"])} <a href="{esc(d["links"]["research_frontier"])}">Research frontier, decoded to the instruction &#8599;</a></p>
  </div>
  <div class="chips">
    <a class="chip" href="{esc(d["links"]["research_frontier"])}">Research diary &#8599;</a>
    <a class="chip" href="{esc(d["links"]["bring_up"])}">Bring-up story &#8599;</a>
    <a class="chip" href="{esc(d["links"]["repo"])}">Repository &#8599;</a>
  </div>

  <div class="stats">{stats}</div>

  <h2>The expedition map</h2>
  <p class="sub">Six of ten stages measured and cleared; the expedition stands at the Front-End Gate.</p>
  <div class="mapwrap">{svg_body}</div>

  <h2>Stages — measured evidence</h2>
  <p class="sub">Every &#8220;cleared&#8221; row was measured in this repo&#8217;s runs, not inferred.</p>
  <div class="card"><table>
    <thead><tr><th>stage</th><th>status</th><th>measured evidence</th><th>what unblocked it</th></tr></thead>
    <tbody>
    {''.join(stage_rows)}
    </tbody>
  </table></div>

  <h2>The fixes</h2>
  <p class="sub">Every wall was decoded to the instruction level, fixed with TDD in the runtime, and verified in long runs.</p>
  <div class="card"><table>
    <thead><tr><th>PR</th><th>fix</th><th>detail</th></tr></thead>
    <tbody>
    {''.join(pr_rows)}
    </tbody>
  </table></div>

  <h3 style="color:#e6edf3;font-size:15px;margin:26px 0 0">Branch-only fixes <span class="mono">(live on <a href="{esc(d["links"]["repo"])}/tree/{esc(d["branch"])}">{esc(d["branch"])}</a>, pending upstream)</span></h3>
  <ul class="fixes">
  {''.join(branch_items)}
  </ul>

  <footer>
    Generated by <code>tools/progress_gen.py</code> from <a href="progress.json">progress.json</a> &#183; data as of {esc(d["updated"])} &#183;
    raw map: <a href="progress.svg">progress.svg</a> &#183; source: <a href="{esc(d["links"]["repo"])}/blob/main/tools/progress_gen.py">tools/progress_gen.py</a><br>
    Color is never the only signal — statuses are also labeled, tooltipped and listed in the tables above (text/table view).
  </footer>
</main>
</body>
</html>
"""


def main():
    src = Path(sys.argv[1]) if len(sys.argv) > 1 else DATA
    data = json.loads(src.read_text(encoding="utf-8"))

    svg_body = build_svg(data)
    SVG_OUT.write_text('<?xml version="1.0" encoding="UTF-8"?>\n' + svg_body + '\n', encoding="utf-8")
    HTML_OUT.write_text(build_html(data, svg_body), encoding="utf-8")

    cleared = sum(1 for s in data["stages"] if s["status"] == "done")
    subs_done = sum(1 for s in data["subsystems"] if s["status"] == "done")
    print(f"progress: {cleared}/{len(data['stages'])} stages cleared, "
          f"{subs_done}/{len(data['subsystems'])} subsystems green")
    print(f"wrote: {SVG_OUT}")
    print(f"wrote: {HTML_OUT}")


if __name__ == "__main__":
    main()
